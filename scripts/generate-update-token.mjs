#!/usr/bin/env node
/**
 * Writes `electron/update-token.ts` — the one place the auto-updater's
 * runtime GitHub token lives — from the `KIYRO_UPDATE_TOKEN` environment
 * variable. Runs before every `build:electron`, dev or release build alike,
 * so that file always exists for `tsc` to compile even when the token isn't
 * set (an empty string, which `electron/updater.ts` treats as "auto-update
 * disabled" rather than a crash).
 *
 * Deliberately not read directly from `process.env` inside `updater.ts`
 * itself: that would read the *end user's* environment at app launch, which
 * is never going to have this variable set — the value has to be baked into
 * the compiled output at build time on the machine that runs
 * `dist:win:publish`, since that's the only place the real secret exists.
 *
 * `electron/update-token.ts` is gitignored on purpose — see README.md's
 * "Releasing and auto-updates" section for why this specific token (not the
 * one used to publish releases) is safe(ish) to ship inside the app, and how
 * to generate/rotate it.
 *
 * `.mjs`, not `.js`: this repo's ESLint config forbids `require()`
 * everywhere, and `package.json` has no `"type": "module"` to make plain
 * `.js` files ESM by default — `.mjs` is what makes `import` both lint-clean
 * and actually runnable via plain `node`, without touching either of those
 * repo-wide settings just for one script.
 */
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const token = process.env.KIYRO_UPDATE_TOKEN ?? '';
const target = path.join(__dirname, '..', 'electron', 'update-token.ts');

const contents = `// AUTO-GENERATED by scripts/generate-update-token.mjs — do not edit by hand,
// and never commit a real value here (this file is gitignored). See
// README.md's "Releasing and auto-updates" section for what this token is,
// why it's separate from the one used to publish releases, and how to
// create/rotate it.
// The \`: string\` annotation matters: without it, \`tsc\` infers this
// \`const\`'s type as the literal token string itself rather than widening it
// to \`string\` — harmless while KIYRO_UPDATE_TOKEN is unset (the literal type
// is then \`""\`, same as what \`updater.ts\` compares against), but the moment
// a real token is baked in, \`updater.ts\`'s \`=== ''\` check becomes a
// comparison between two string literal types with no overlap, which \`tsc\`
// correctly refuses to compile.
export const UPDATE_FEED_TOKEN: string = ${JSON.stringify(token)};
`;

fs.writeFileSync(target, contents, 'utf-8');

if (token === '') {
  console.warn(
    '[kiyro] KIYRO_UPDATE_TOKEN is not set — this build will have auto-update disabled.',
  );
}
