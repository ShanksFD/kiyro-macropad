#!/usr/bin/env node
/**
 * Writes every gitignored `electron/*-secret.ts` / `electron/update-token.ts`
 * file Kiyro bakes a build-time secret into, from environment variables.
 * Runs before every `build:electron` — dev or release build alike — so
 * those files always exist for `tsc` to compile even when a given secret
 * isn't set (an empty string, which each secret's own consumer treats as
 * "this feature is disabled" rather than a crash).
 *
 * One script for all of them rather than one per secret: they're the exact
 * same shape (env var in, gitignored `.ts` file with a typed `const` out),
 * and duplicating that boilerplate per-secret would just be more places for
 * the `: string` annotation bug (see the comment in the generated file
 * below) to sneak back in.
 *
 * Deliberately not read directly from `process.env` inside the files that
 * *use* these secrets: that would read the *end user's* environment at app
 * launch, which is never going to have any of these set — the values have
 * to be baked into the compiled output at build time, on the machine that
 * actually has them.
 *
 * `.mjs`, not `.js`: this repo's ESLint config forbids `require()`
 * everywhere, and `package.json` has no `"type": "module"` to make plain
 * `.js` files ESM by default — `.mjs` is what makes `import` both lint-clean
 * and actually runnable via plain `node`.
 */
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const electronDir = path.join(__dirname, '..', 'electron');

/**
 * Each entry: the env var that supplies the real value, the exported
 * constant name, the file it's written to, and a one-line pointer to where
 * that secret is documented (creation, rotation, what it's for).
 */
const SECRETS = [
  {
    env: 'KIYRO_UPDATE_TOKEN',
    exportName: 'UPDATE_FEED_TOKEN',
    file: 'update-token.ts',
    docs: 'README.md\'s "Releasing and auto-updates" section',
  },
  {
    env: 'KIYRO_DISCORD_CLIENT_SECRET',
    exportName: 'DISCORD_CLIENT_SECRET',
    file: 'discord-secret.ts',
    docs: 'README.md\'s "Discord integration" section',
  },
  {
    // Not actually a secret — a Sentry DSN is designed to be public and
    // ships in every client SDK by definition (it only authorizes *writing*
    // events to one project). It goes through this pipeline anyway because
    // the shape is identical, and because it keeps "this build reports
    // crashes" a property of the build environment rather than something
    // committed once and impossible to turn off per-build.
    env: 'KIYRO_SENTRY_DSN',
    exportName: 'SENTRY_DSN',
    file: 'sentry-dsn.ts',
    docs: 'README.md\'s "Crash and error reporting" section',
  },
];

for (const { env, exportName, file, docs } of SECRETS) {
  const value = process.env[env] ?? '';
  const target = path.join(electronDir, file);

  const contents = `// AUTO-GENERATED by scripts/generate-build-secrets.mjs from $${env} — do not
// edit by hand, and never commit a real value here (this file is
// gitignored). See ${docs} for what this is and how to create/rotate it.
//
// The \`: string\` annotation matters: without it, \`tsc\` infers this
// \`const\`'s type as the literal secret string itself rather than widening it
// to \`string\` — harmless while ${env} is unset (the literal type is then
// \`""\`), but the moment a real value is baked in, any \`=== ''\` check
// against it becomes a comparison between two string literal types with no
// overlap, which \`tsc\` correctly refuses to compile.
export const ${exportName}: string = ${JSON.stringify(value)};
`;

  fs.writeFileSync(target, contents, 'utf-8');

  if (value === '') {
    console.warn(`[kiyro] ${env} is not set — this build will have that feature disabled.`);
  }
}
